// Refresh the approved, portable snapshot. Normal builds need no external checkout.
import { readFile, writeFile, mkdir, cp, readdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import crypto from "node:crypto";

const root = fileURLToPath(new URL("../", import.meta.url));
const input = process.argv[2];
if (!input) throw new Error("Usage: node scripts/sync-brand.mjs /path/to/relayna-design-system");
const source = path.resolve(input);
const brand = JSON.parse(await readFile(path.join(source, "source/brand.json"), "utf8"));
if (brand.system !== "Natural Connection" || brand.palette !== "Mulberry & Linen" || brand.logo.name !== "Slim Leaf") throw new Error("Expected the approved Natural Connection / Mulberry & Linen / Slim Leaf identity.");
const target = path.join(root, "docs/assets/brand");
const ui = path.join(root, "crates/gateway-api/admin-ui/src");
await mkdir(target, { recursive: true });
const sourceManifest = JSON.parse(await readFile(path.join(source, "dist/manifest.json"), "utf8"));
const hash = data => crypto.createHash("sha256").update(data).digest("hex");
const copied = {};
async function copy(from, to) {
  const data = await readFile(path.join(source, from));
  if (sourceManifest.files[from] && sourceManifest.files[from] !== hash(data)) throw new Error(`Source checksum mismatch: ${from}`);
  await mkdir(path.dirname(path.join(target, to)), { recursive: true });
  await writeFile(path.join(target, to), data);
  copied[to] = hash(data);
}
await copy("source/brand.json", "identity.json");
await copy("source/pictograms.json", "pictograms.json");
await copy("dist/tokens/resolved.json", "tokens.json");
await copy("dist/tokens/design-tokens.json", "design-tokens.json");
await copy("dist/css/tokens.css", "tokens.css");
await copy("dist/fonts/RelaynaPortico-Variable.woff2", "fonts/RelaynaPortico-0.100.woff2");
await copy("dist/fonts/RelaynaPortico-VariableItalic.woff2", "fonts/RelaynaPortico-Italic-0.100.woff2");
for (const name of await readdir(path.join(source, "dist/assets/logos"))) await copy(`dist/assets/logos/${name}`, `logos/${name}`);
for (const folder of ["pictograms", "illustrations"]) {
  for (const name of await readdir(path.join(source, "dist/assets", folder))) {
    if (name.endsWith(".svg")) await copy(`dist/assets/${folder}/${name}`, `${folder}/${name}`);
  }
}
for (const name of await readdir(path.join(source, "dist/assets/banners"))) {
  if (name.endsWith(".svg") && (name.includes("-wide-") || name.startsWith("natural-connection-family-") || name.startsWith("open-signal-family-"))) await copy(`dist/assets/banners/${name}`, `banners/${name}`);
}
await copy("dist/assets/favicon.ico", "favicon.ico");
const snapshot = JSON.parse(await readFile(path.join(target, "tokens.json"), "utf8"));
const primitiveNames = Object.fromEntries(Object.entries(snapshot.primitives).map(([name, hex]) => [hex, name]));
const material = Object.entries(snapshot.themes).map(([mode, tokens]) => `[data-md-color-scheme="${mode === "dark" ? "slate" : "default"}"] {\n${Object.entries(tokens).map(([name, hex]) => `  --rn-${name}: var(--rn-primitive-${primitiveNames[hex]});`).join("\n")}\n}`).join("\n");
await writeFile(path.join(target, "material-tokens.css"), "/* Generated by scripts/sync-brand.mjs. */\n" + material);
copied["material-tokens.css"] = hash(await readFile(path.join(target, "material-tokens.css")));
await mkdir(path.join(root, "crates/gateway-api/admin-ui/public"), { recursive: true });
await cp(path.join(target, "favicon.ico"), path.join(root, "crates/gateway-api/admin-ui/public/favicon.ico"));
await cp(path.join(target, "tokens.css"), path.join(ui, "design-system/brand-tokens.css"));

// Keep the actual outlined paths. The config's pre-renderer can render native
// JSX without a special SVG loader or runtime asset fetch.
const logo = await readFile(path.join(target, "logos/relayna-gateway-light.svg"), "utf8");
const viewBox = logo.match(/viewBox="([^"]+)"/)[1];
const body = logo.replace(/^<svg[^>]+>/, "").replace(/<\/svg>$/, "").replace(/<title>.*?<\/title>/, "").replace(/\s+id="[^"]+"/g, "")
  .replaceAll(brand.anchors.mulberry, "var(--rg-brand-body)").replaceAll(brand.anchors.rose, "var(--rg-brand-relay)");
const artwork = await readFile(path.join(target, "illustrations/relayna-gateway-open-signal-light.svg"), "utf8");
const artViewBox = artwork.match(/viewBox="([^"]+)"/)[1];
const artBody = artwork.replace(/^<svg[^>]+>/, "").replace(/<\/svg>$/, "")
  .replaceAll(brand.anchors.mulberry, "var(--rn-color-brand-frame)")
  .replaceAll(brand.anchors.rose, "var(--rn-color-brand-leaf)")
  .replaceAll(snapshot.themes.light["color-pictogram-accent"], "var(--rn-color-pictogram-accent)")
  .replaceAll(snapshot.themes.light["color-surface-subtle"], "var(--rn-color-surface-subtle)")
  .replaceAll("stroke-width=", "strokeWidth=").replaceAll("stroke-linecap=", "strokeLinecap=")
  .replaceAll("stroke-linejoin=", "strokeLinejoin=").replaceAll("fill-rule=", "fillRule=");
await writeFile(path.join(ui, "react/brand.tsx"), `/** Generated by scripts/sync-brand.mjs from the approved native SVG masters. */\nexport function RelaynaLogo() {\n  return (<svg className="relayna-logo" viewBox="${viewBox}" role="img" aria-label="relayna Gateway" focusable="false">${body}</svg>);\n}\nexport function GatewaySignalArtwork() {\n  return (<svg className="gateway-signal-artwork" viewBox="${artViewBox}" preserveAspectRatio="xMidYMid meet" aria-hidden="true" focusable="false">${artBody}</svg>);\n}\n`);
await writeFile(path.join(ui, "brand-identity.ts"), `// Generated by scripts/sync-brand.mjs. Approved copy and palette.\nexport const brandIdentity = ${JSON.stringify(brand, null, 2)} as const;\n`);
await writeFile(path.join(target, "manifest.json"), JSON.stringify({ version: brand.version, source: "@relayna/design-system", selection: { system: brand.system, palette: brand.palette, logo: brand.logo.name }, files: Object.entries(copied).map(([path, sha256]) => ({ sha256, path })) }, null, 2) + "\n");
console.log(`Synced ${Object.keys(copied).length} approved brand assets, native JSX and exact copy.`);
